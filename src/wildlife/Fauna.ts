export const FAUNA_PROFILES: readonly FaunaProfile[] = [
  ...BASE_FAUNA_PROFILES,
  ...ANTELOPE_PROFILES,
  ...BOVID_PROFILES,
  ...PATTERNED_GRAZER_PROFILES,
  PANDA_PROFILE,
  ...UNGULATE_PROFILES,
  ...PET_ART.map((art): FaunaProfile => {
    const base = BASE_FAUNA_PROFILES.find((p) => p.species === art.species);
    if (!base) throw new Error(`Missing pet behavior: ${art.species}`);
    // Each immutable coat bank owns its frame ranges independently of base repairs.
    const count = art.walkCount;
    return {
      ...base,
      species: art.id,
      variantOf: art.species,
      label: art.name,
      image: `demos/wildlife-v2/${art.id}/draft-v1/sheet.png`,
      identity: art.identity,
      sha256: art.sha256,
      inspection: art.inspection,
      // Match linear travel to the authored four/six-pixel walk stride.
      speed: art.stridePixels / (count * 0.08),
      step: art.species === "cat" ? 12 : 16,
      clips: [
        { name: "idle", start: 0, count: 1, frameDuration: 160, loop: true },
        { name: "walk", start: 1, count, frameDuration: 80, loop: true },
        { name: "action", start: 1 + count, count: 8, frameDuration: 160, loop: false },
        { name: "flee", start: 1, count, frameDuration: 40, loop: true },
      ],
    };
  }),
];
/** Same cat/dog habitat owner, independent deterministic coat choice. */
export function petCoat(species: "cat" | "dog", roll: number): FaunaSpecies {
  const coats: FaunaSpecies[] = [
    species,
    ...PET_ART.filter((a) => a.species === species).map((a) => a.id),
  ];
  return coats[Math.min(coats.length - 1, Math.max(0, Math.floor(roll * coats.length)))] ?? species;
}
export const faunaType = (species: FaunaSpecies) => `wildlife-${species}-provisional-v1`;
const profilesByType = new Map(FAUNA_PROFILES.map((p) => [faunaType(p.species), p]));
export const faunaProfile = (type: string | undefined) =>
  type === undefined ? undefined : profilesByType.get(type);
export interface FaunaBehavior {
  home: PositionComponent;
  shelter: PositionComponent;
  radius: number;
  groupId?: string;
  /** Optional planner-owned safe yard in world pixels; persisted with the individual. */
  habitatBounds?: { minX: number; minY: number; maxX: number; maxY: number };
  state: "rest" | "action" | "startle" | "travel" | "flee" | "recover";
  timer: number;
  randomState: number;
  activity: number;
  target: PositionComponent;
  water?: boolean;
  actionElapsed?: number;
  alarmFrom?: PositionComponent;
  motion?: { elapsed: number; duration: number; escaping: boolean; startZ?: number; endZ?: number };
}
export function faunaDefinition(p: FaunaProfile) {
  const walk = p.clips[1];
  const rideSpeed = p.rideSpeed;
  return {
    sprite: {
      sheetKey: faunaType(p.species),
      spriteWidth: p.size,
      spriteHeight: p.size,
      frameCount: 1,
      frameDuration: p.clips[0]?.frameDuration ?? 100,
      drawOffsetY: p.size - p.anchor[1],
      clips:
        rideSpeed && walk
          ? [
              ...p.clips,
              ...[1, 2].map((multiplier) => ({
                ...walk,
                name: multiplier === 1 ? "ride" : "ride-sprint",
                frameDuration: (walk.frameDuration * p.speed) / (rideSpeed * multiplier),
              })),
            ]
          : p.clips,
    },
    collider: {
      offsetX: 0,
      offsetY: 0,
      width: p.body[0],
      height: p.body[1],
      physicalHeight: p.body[2],
      solid: true,
    },
    aquatic: p.habitat === "pond" || p.habitat === "deep",
    amphibious: p.habitat === "shore",
    hasVelocity: true,
    weight: Math.max(1, p.body[0] * 2),
    wanderAI: {
      idleMin: 2,
      idleMax: 6,
      walkMin: 1,
      walkMax: 3,
      speed: p.speed,
      directional: true,
      ...(p.rideSpeed ? { rideSpeed: p.rideSpeed } : {}),
    },
  } satisfies EntityDef;
}
export const FAUNA_DEFS: Record<string, EntityDef> = Object.fromEntries(
  FAUNA_PROFILES.map((p) => [faunaType(p.species), faunaDefinition(p)]),
);
export function createFauna(species: FaunaSpecies, wx: number, wy: number): Entity {
  const type = faunaType(species),
    p = faunaProfile(type);
  if (!p) throw new Error(`Unavailable fauna profile: ${species}`);
  const d = faunaDefinition(p);
  return {
    id: 0,
    type,
    wz: 0,
    position: { wx, wy },
    velocity: { vx: 0, vy: 0 },
    sprite: {
      ...d.sprite,
      frameCol: 0,
      frameRow: 0,
      animTimer: 0,
      direction: Direction.Down,
      moving: false,
      clip: 0,
    },
    collider: { ...d.collider },
    wanderAI: { ...d.wanderAI, state: "idle", timer: 0, dirX: 0, dirY: 0 },
    fauna: {
      water: d.aquatic,
      home: { wx, wy },
      shelter: { wx, wy },
      radius: p.radius,
      state: "rest",
      timer: 2,
      randomState: ((Math.floor(wx) * 73856093) ^ (Math.floor(wy) * 19349663) ^ 8001) >>> 0,
      activity: 0,
      target: { wx, wy },
    },
    noShadow: d.aquatic,
    weight: d.weight ?? 1,
    tags: new Set(["npc", "wildlife", ...(p.rideSpeed ? ["rideable"] : [])]),
  };
}
export const FAUNA_FACTORIES: Record<string, (wx: number, wy: number) => Entity> =
  Object.fromEntries(
    FAUNA_PROFILES.map((p) => [
      faunaType(p.species),
      (wx: number, wy: number) => createFauna(p.species, wx, wy),
    ]),
  );
