def png(path, w, h, pixels):
    def chunk(k, v):
        return (
            struct.pack(">I", len(v))
            + k
            + v
            + struct.pack(">I", zlib.crc32(k + v) & 0xFFFFFFFF)
        )

    raw = b"".join(b"\0" + pixels[y * w * 4 : (y + 1) * w * 4] for y in range(h))
    path.write_bytes(
        b"\x89PNG\r\n\x1a\n"
        + chunk(b"IHDR", struct.pack(">IIBBBBB", w, h, 8, 6, 0, 0, 0))
        + chunk(b"IDAT", zlib.compress(raw, 9))
        + chunk(b"IEND", b"")
    )


def framed(x, z, x0, x1, z0, z1):
    if x0 <= x <= x1 and z0 <= z <= z1:
        if min(x - x0, x1 - x) < 0.055 or min(z - z0, z1 - z) < 0.055:
            return "ink"
        f = (z - z0) / (z1 - z0)
        return (
            "glassGlint" if 0.68 < f < 0.79 else "glassLight" if f > 0.44 else "glass"
        )
    return None


def cab_side(x, z):
    k = framed(
        x, z, -2.78 + 0.26 * max(0, min(1, (z - 1.53) / 0.95)), -1.22, 1.53, 2.48
    )
    if k:
        return k
    if abs(x + 1.10) < 0.018 and 0.62 < z < 2.66:
        return "paintDeep"
    if -1.31 < x < -1.10 and 1.40 < z < 1.46:
        return "ink"
    return "paintLight" if z > 2.48 else "paint" if z > 1.40 else "paintMid"


