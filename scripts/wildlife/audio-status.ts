import { readFileSync, writeFileSync } from "node:fs";
import {
  ANIMAL_VOICES,
  animalSoundCoverage,
  animalVoiceForSpecies,
} from "../../src/audio/AnimalVoice.js";
import { predatorProfile } from "../../src/wildlife/Predator.js";
import { ANIMAL_BROWSER_ENTRIES } from "../../src/workshop/AnimalBrowserData.js";

const path = "docs/wildlife-audio-audit.md";
const ledger = JSON.parse(
  readFileSync("art-source/wildlife-v2/behavior-campaign.json", "utf8"),
) as {
  animals: Record<string, { runtimeType: string }>;
};
const rows = ANIMAL_BROWSER_ENTRIES.map((a) => {
  if (ledger.animals[a.id]?.runtimeType !== a.type)
    throw Error(`Animal audio identity drift: ${a.id}`);
  const coverage = animalSoundCoverage(a.type),
    voice = animalVoiceForSpecies(a.id),
    profile = predatorProfile(a.type);
  const design = voice
    ? `recorded ${voice}`
    : (profile?.callKind ??
      profile?.fierce?.kind ??
      (a.id === "robin"
        ? "robin chirp"
        : a.id === "frog"
          ? "frog croak"
          : a.id === "mallard"
            ? "duck quack"
            : null));
  return {
    ...a,
    coverage,
    design,
    note: voice
      ? ANIMAL_VOICES[voice].label + (a.id !== voice ? "; inherited base voice" : "")
      : a.id === "owl"
        ? "Configured hoot selected; raptor locomotion is separate"
        : ["panther", "tiger", "lion", "brown-bear"].includes(a.id)
          ? "Display animation exists; no call kind"
          : "",
  };
}).sort((a, b) => a.family.localeCompare(b.family) || a.id.localeCompare(b.id));
if (
  new Set(rows.map((a) => a.id)).size !== rows.length ||
  rows.length !== Object.keys(ledger.animals).length
)
  throw Error("Animal audio roster mismatch");
const count = (coverage: string) => rows.filter((a) => a.coverage === coverage).length;
const covered = rows.filter((a) => a.coverage !== "missing").length;
const text = (s: string) => s.replaceAll("|", "/").replace(/[\r\n]/g, " ");
const lines = [
  "# Animal sound coverage audit",
  "",
  "Current source inventory. Generated by `npx tsx scripts/wildlife/audio-status.ts`; use `--check` to verify freshness.",
  "",
  "[Sound plan, delivery status and source credits](topics/wildlife-audio.md).",
  "",
  `**${rows.length} entries: ${covered} have call routes (${count("recorded")} recorded, ${count("synthesized")} synthesized, ${count("game-only")} game only); ${count("missing")} have no call route.**`,
  "",
  `There are ${new Set(rows.filter((a) => a.design).map((a) => a.design)).size} effective voice designs. Coats/shared voices count as entry coverage, not unique designs. Recorded voices are integrated; owner listening approval remains pending.`,
  "",
  "No call route means no species call wiring was found, not that the actor can never make generic collision/ball-hit audio. It does not classify the animal as intentionally quiet. Movement/interaction Foley remains separate.",
  "",
  "Recorded calls share AnimalAudio in game and lab, using replicated named action poses and sparse local idle ambience. Shared hunter synthesis uses `callKind ?? fierce.kind` and clip transitions. Robin/frog/mallard remain in the ordinary PlayScene path. Lab sounds require opt-in; recorded auditions are separate explicit button gestures.",
  "",
  "Evidence: [recorded voice mapping](../src/audio/AnimalVoice.ts), [shared recorded playback](../src/audio/AnimalAudio.ts), [shared synthesis](../src/audio/AudioManager.ts), [game-only calls](../src/scenes/PlayScene.ts), [familiar receipts](../art-source/animal-audio/familiar-v1/manifest.json), [farm receipts](../art-source/animal-audio/farm-v1/manifest.json), [bird receipts](../art-source/animal-audio/garden-birds-v1/manifest.json).",
  "",
  "| Animal ID | Animal | Runtime type | Effective call | Coverage | Audit note |",
  "| --- | --- | --- | --- | --- | --- |",
  ...rows.map(
    (a) =>
      `| ${a.id} | ${text(a.name)} | ${a.type} | ${a.design ?? "—"} | ${a.coverage} | ${a.note} |`,
  ),
  "",
];
const output = lines.join("\n");
if (process.argv.includes("--check")) {
  if (readFileSync(path, "utf8").replaceAll("\r\n", "\n") !== output)
    throw Error("Animal audio audit is stale");
} else writeFileSync(path, output);
console.log(
  JSON.stringify({
    entries: rows.length,
    covered,
    recorded: count("recorded"),
    synthesized: count("synthesized"),
    gameOnly: count("game-only"),
    missing: count("missing"),
  }),
);
